def build_flashcards(n: int, ch: dict) -> list:
    """Generate ~5-8 flashcards per chapter from the chapter content."""
    cards = []
    # Concept card 1 — chapter title and brief
    cards.append({
        "id": f"fc-{n:02d}-01",
        "chapter": n,
        "kind": "concept",
        "front": f"Chapter {n}: What does '{ch['title']}' mean in Python?",
        "back": ch["brief"],
    })
    # Syntax card
    syn = build_syntax_blocks(n)[0]
    code_str = syn["code"]
    cards.append({
        "id": f"fc-{n:02d}-02",
        "chapter": n,
        "kind": "syntax",
        "front": f"Write the canonical syntax for: {ch['title']}",
        "back": code_str,
        "code": code_str,
    })
    # Output card (if there's an output)
    if syn.get("output"):
        cards.append({
            "id": f"fc-{n:02d}-03",
            "chapter": n,
            "kind": "output",
            "front": "Predict the output of:",
            "back": syn["output"],
            "code": code_str,
        })
    # Example card
    examples = build_examples(n)
    if examples:
        ex = examples[0]
        cards.append({
            "id": f"fc-{n:02d}-04",
            "chapter": n,
            "kind": "output",
            "front": f"Example — {ex['description']}. Predict the output of:",
            "back": ex["code"].get("output", "(no output)"),
            "code": ex["code"]["code"],
        })
    # Mistake card
    mistakes = build_mistakes(n)
    if mistakes:
        m = mistakes[0]
        cards.append({
            "id": f"fc-{n:02d}-05",
            "chapter": n,
            "kind": "mistake",
            "front": f"What's wrong with this code?\n{m['wrong']}",
            "back": f"Correct: {m['correct']}\n\nWhy: {m['explanation']}",
        })
    # Revision bullet card
    revision = build_revision(n)
    cards.append({
        "id": f"fc-{n:02d}-06",
        "chapter": n,
        "kind": "concept",
        "front": "Quick revision — name the key takeaway of this chapter.",
        "back": "\n".join("• " + r for r in revision),
    })
    # Mini-quiz card from slide quiz
    quiz = build_quiz_for_slide(n)
    opts = "\n".join(f"{chr(65+i)}) {o}" for i, o in enumerate(quiz["options"]))
    correct_letter = chr(65 + quiz["correctIndex"])
    cards.append({
        "id": f"fc-{n:02d}-07",
        "chapter": n,
        "kind": "concept",
        "front": f"Quiz: {quiz['question']}\n\n{opts}",
        "back": f"Answer: {correct_letter}) {quiz['options'][quiz['correctIndex']]}\n\n{quiz['explanation']}",
    })
    return cards


